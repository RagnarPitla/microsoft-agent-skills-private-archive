function skillCard(s) {
  const badge = s.userInvoked
    ? '<span class="badge you">You invoke it</span>'
    : '<span class="badge auto">Automatic</span>';
  return `          <a class="skill" href="${esc(s.bucket)}/${esc(s.name)}.html">
            <h3>${esc(s.displayName || s.name)}</h3>
            <p>${esc(s.shortDescription || "")}</p>
            <footer><code>${esc(s.name)}</code>${badge}</footer>
          </a>`;
}

function bucketSection(bucket, skills) {
  const inBucket = skills.filter((s) => s.bucket === bucket);
  if (!inBucket.length) return "";
  const cards = inBucket
    .slice()
    .sort((a, b) => a.name.localeCompare(b.name))
    .map(skillCard)
    .join("\n");
  return `        <div class="bucket" id="${esc(bucket)}">
          <div class="bucket-head">
            <span class="pill">${esc(bucket)}</span>
            <p>${esc(BUCKET_BLURB[bucket] || "")}</p>
          </div>
          <div class="skills">
${cards}
          </div>
        </div>`;
}

function installCard(name, blocks) {
  const cmds = blocks.map((b) => `<pre><code>${esc(b)}</code></pre>`).join("\n            ");
  return `          <article class="install">
            <h3>${esc(name)}</h3>
            <p>${esc(INSTALL_NOTES[name] || "")}</p>
            ${cmds}
          </article>`;
}

/**
 * The ordered list of promoted skills, as the layout needs it.
 * Ordered by bucket then name so "previous" and "next" walk the same sequence a
 * reader sees on the landing page.
 */
export function orderedSkills(skills) {
  return skills
    .filter((s) => s.promoted)
    .slice()
    .sort((a, b) => PROMOTED.indexOf(a.bucket) - PROMOTED.indexOf(b.bucket) || a.name.localeCompare(b.name));
}

/**
 * Emits docs/_data/skills.yml. The layout reads it to put a skill's invocation
 * model, bucket and source link on its page, so none of that is retyped into
 * the Markdown where it could drift from the skill it describes.
 */
export function buildSkillsData(skills) {
  const ordered = orderedSkills(skills);
  const lines = [`# ${BANNER}`];

  ordered.forEach((s, i) => {
    const prev = ordered[i - 1];
    const next = ordered[i + 1];
    const f = (k, v) => (v === undefined || v === null ? null : `  ${k}: ${JSON.stringify(v)}`);
    lines.push(
      [
        f("name", s.name),
        f("title", s.displayName || s.name),
        f("short", s.shortDescription || ""),
        f("bucket", s.bucket),
        f("user_invoked", Boolean(s.userInvoked)),
        f("url", `/${s.bucket}/${s.name}.html`),
        f("source", `${REPO}/blob/main/skills/${s.bucket}/${s.name}/SKILL.md`),
        prev && f("prev", prev.displayName || prev.name),
        prev && f("prev_url", `/${prev.bucket}/${prev.name}.html`),
        next && f("next", next.displayName || next.name),
        next && f("next_url", `/${next.bucket}/${next.name}.html`),
      ]
        .filter(Boolean)
        .join("\n")
        .replace(/^ {2}/, "- "),
    );
  });

  return `${lines.join("\n")}\n`;
}

