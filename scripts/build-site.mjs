const realpathOrNull = (p) => {
  try {
    return realpathSync(p);
  } catch {
    return null;
  }
};
const invokedAs = process.argv[1] && realpathOrNull(path.resolve(process.argv[1]));
const isMain = Boolean(invokedAs) && invokedAs === realpathOrNull(fileURLToPath(import.meta.url));

if (isMain) {
  const skills = loadSkills();
  const installBlock = parseInstallBlock(readFileSync(path.join(ROOT, ".agents/install-block.md"), "utf8"));
  const artefacts = new Map([
    [SITE_PAGE, buildSite(skills, installBlock)],
    [SITE_DATA, buildSkillsData(skills)],
  ]);
  const count = skills.filter((s) => s.promoted).length;

  if (process.argv.includes("--check")) {
    const stale = [...artefacts].filter(([rel, content]) => {
      const abs = path.join(ROOT, rel);
      return (existsSync(abs) ? readFileSync(abs, "utf8") : null) !== content;
    });

    if (stale.length) {
      console.error("Site artefacts are out of date:\n");
      stale.forEach(([rel]) => console.error(`  stale: ${rel}`));
      console.error("\nRun `npm run build` and commit the result.");
      process.exit(1);
    }
    console.log(`Site artefacts up to date (${artefacts.size} files from ${count} skills).`);
    process.exit(0);
  }

  for (const [rel, content] of artefacts) {
    const abs = path.join(ROOT, rel);
    mkdirSync(path.dirname(abs), { recursive: true });
    writeFileSync(abs, content, "utf8");
  }
  console.log(`Built ${artefacts.size} site artefact(s) from ${count} promoted skill(s).`);
}
