/**
 * Pull the fenced command blocks out of .agents/install-block.md, keyed by its
 * `## ` headings. Parsed rather than duplicated so the site cannot drift from
 * the wording the README is also required to match.
 */
export function parseInstallBlock(md) {
  const out = new Map();
  const sections = String(md).split(/^## /m).slice(1);
  for (const section of sections) {
    const name = section.slice(0, section.indexOf("\n")).trim();
    const blocks = [...section.matchAll(/```[a-z]*\n([\s\S]*?)```/g)].map((m) => m[1].trim());
    if (blocks.length) out.set(name, blocks);
  }
  return out;
}

